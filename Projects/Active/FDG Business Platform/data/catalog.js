export const BASE_ROLES = ["Owner", "Administrator", "Manager", "Supervisor", "Staff", "Cashier", "Accountant", "Viewer"];

export function getModule(id) {
  return MODULES.find((module) => module.id === id) ?? MODULES[0];
}

export function planTotal(plan, branches = 1) {
  return plan.basePrice + Math.max(0, Number(branches) - 1) * plan.branchPrice;
}

export function peso(centavos) {
  return new Intl.NumberFormat("en-PH", { style: "currency", currency: "PHP", maximumFractionDigits: 0 }).format(centavos / 100);
}
